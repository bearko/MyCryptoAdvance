export const CHAR_W = 3;
export const CHAR_H = 5;

export function textWidth(text) {
  return text.length * (CHAR_W + 1) - 1;
}

/** 1px の影付きで文字を打つ */
export function drawText(ctx, text, x, y, color = '#fff', shadow = 'rgba(0,0,0,0.6)') {
  const s = String(text).toUpperCase();
  for (const pass of shadow ? [shadow, color] : [color]) {
    const ox = pass === shadow ? 1 : 0;
    const oy = pass === shadow ? 1 : 0;
    ctx.fillStyle = pass;
    let cx = x + ox;
    for (const ch of s) {
      const g = G[ch] || G[' '];
      for (let ry = 0; ry < CHAR_H; ry++) {
        const row = g[ry];
        for (let rx = 0; rx < CHAR_W; rx++) {
          if (row[rx] === '#') ctx.fillRect(cx + rx, y + oy + ry, 1, 1);
        }
      }
      cx += CHAR_W + 1;
    }
  }
}
